// Writes shell/src/app/builtins.gen.ts: one entry for every plugin in plugins/ that has a client half
// (`src/client.tsx`), so adding a plugin needs no edit to the shell. The file is generated before
// typecheck, test, build and dev, and is not committed. It goes with builtins.ts in M2, once Rookery
// serves plugins' client halves.
import { existsSync, readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dir, "..")
const plugins = readdirSync(join(root, "plugins"), { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .filter((name) => existsSync(join(root, "plugins", name, "plugin.json")))
  .filter((name) => existsSync(join(root, "plugins", name, "src", "client.tsx")))
  .sort()

const ident = (name: string) =>
  name.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c: string | undefined) => (c ?? "").toUpperCase())

const lines = [
  "// Generated by scripts/builtins.ts from plugins/*: do not edit.",
  ...plugins.map((name) => `import ${ident(name)} from "../../../plugins/${name}/plugin.json"`),
  "",
  "export const BUILTIN_SOURCES = [",
  ...plugins.map(
    (name) => `  { manifest: ${ident(name)}, load: () => import("../../../plugins/${name}/src/client") },`,
  ),
  "] as const",
  "",
]

const out = join(root, "shell", "src", "app", "builtins.gen.ts")
writeFileSync(out, lines.join("\n"))
console.log(`[builtins] ${plugins.join(", ")}`)
