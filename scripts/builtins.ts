// Writes shell/src/app/builtins.gen.ts: one entry for every plugin in plugins/ that has a client half
// (`src/client.tsx`), so `bun run dev` and the tests need no server that serves plugins. The file is
// generated before typecheck, test, build and dev, and is not committed.
//
// The packaged shell loads the plugins a Rookery server serves instead (`plugins.list`); see
// `src/app/state.ts` for when these are used. A plugin's manifest is `rookery/plugin.json`, the target
// Rookery's `schemas/plugin.schema.json` describes.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dir, "..")

/** The manifest of a plugin's folder, as it is in the source tree. */
function manifestOf(name: string): string | null {
  const path = "rookery/plugin.json"
  if (existsSync(join(root, "plugins", name, path))) return `../../../plugins/${name}/${path}`
  return null
}

const plugins = readdirSync(join(root, "plugins"), { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .map((name) => ({ name, manifest: manifestOf(name) }))
  .filter((p): p is { name: string; manifest: string } => p.manifest !== null)
  .filter((p) => existsSync(join(root, "plugins", p.name, "src", "client.tsx")))
  .sort((a, b) => a.name.localeCompare(b.name))

const ident = (name: string) =>
  name.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c: string | undefined) => (c ?? "").toUpperCase())

const version = (name: string) =>
  JSON.parse(readFileSync(join(root, "plugins", name, "package.json"), "utf8")).version as string

const lines = [
  "// Generated by scripts/builtins.ts from plugins/*: do not edit.",
  ...plugins.map((p) => `import ${ident(p.name)}Manifest from "${p.manifest}"`),
  "",
  "export const BUILTIN_SOURCES = [",
  ...plugins.map(
    (p) =>
      `  { id: ${JSON.stringify(p.name)}, version: ${JSON.stringify(version(p.name))}, manifest: ${ident(p.name)}Manifest, load: () => import("../../../plugins/${p.name}/src/client") },`,
  ),
  "] as const",
  "",
]

const out = join(root, "shell", "src", "app", "builtins.gen.ts")
writeFileSync(out, lines.join("\n"))
console.log(`[builtins] ${plugins.map((p) => p.name).join(", ")}`)
